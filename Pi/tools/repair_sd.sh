#!/usr/bin/env bash
#
# repair_sd.sh — apply fixes to an already-installed card, from a machine that
# can only write its boot partition.
#
# On macOS the payload's ext4 root mounts read-only, so a card that has already
# been installed cannot simply be edited. This writes a one-shot script to the
# FAT32 boot partition and hooks it into the kernel command line, exactly as
# first-boot customisation does. On the next boot it applies the fixes as root
# and then removes both itself and its hook.
#
# It exists because the alternative -- reflashing a card to change two lines in
# /etc -- throws away the flight data on it.
#
set -euo pipefail

BOOT_PATH=""
DRY_RUN=0

usage() {
    cat <<'USAGE'
Usage: repair_sd.sh [--boot PATH] [--dry-run]

Applies to the next boot:
  * WiFi power saving off. A sleeping adapter holds its association and its
    DHCP lease while dropping inbound frames, so the payload looks dead while
    it is working perfectly.
  * usb0 and usb1 marked unmanaged in NetworkManager, so the gadget script's
    static address survives instead of being replaced by a DHCP attempt
    against a cable with no server on it.
USAGE
}

while [[ $# -gt 0 ]]; do
    case "$1" in
        --boot)    BOOT_PATH="${2:?--boot needs a path}"; shift ;;
        --dry-run) DRY_RUN=1 ;;
        -h|--help) usage; exit 0 ;;
        *) echo "unknown option: $1" >&2; usage; exit 1 ;;
    esac
    shift
done

ok()   { printf '  \033[32mok\033[0m   %s\n' "$*"; }
warn() { printf '  \033[33mwarn\033[0m %s\n' "$*"; }
die()  { printf '\033[31merror\033[0m %s\n' "$*" >&2; exit 1; }

if [[ -z "$BOOT_PATH" ]]; then
    for c in /Volumes/bootfs /Volumes/boot /media/"$USER"/bootfs \
             /run/media/"$USER"/bootfs; do
        [[ -d "$c" ]] && { BOOT_PATH="$c"; break; }
    done
fi
[[ -n "$BOOT_PATH" && -f "$BOOT_PATH/cmdline.txt" ]] \
    || die "No Raspberry Pi boot partition found. Pass --boot."

echo
echo "RaptorHAB card repair"
echo "====================="
ok "boot partition: $BOOT_PATH"

REPAIR_BODY='#!/bin/bash
# Generated by RaptorHAB repair_sd.sh. Runs once, as root, on boot.
set +e
LOG=/var/log/raptorhab-repair.log
exec >>$LOG 2>&1
echo "--- RaptorHAB repair: $(date) ---"

install -d -m 0755 /etc/NetworkManager/conf.d

cat > /etc/NetworkManager/conf.d/10-raptorhab-wifi-powersave.conf <<CONF
# 2 = disable power saving. A sleeping adapter loses inbound packets while
# still holding its association and lease, which is indistinguishable from a
# hung payload right up until you recover the card.
[connection]
wifi.powersave = 2
CONF
echo "wifi power saving disabled"

cat > /etc/NetworkManager/conf.d/10-raptorhab-usb0-unmanaged.conf <<CONF
# The gadget script gives this interface a static address. NetworkManager must
# not also DHCP it: there is no server on the other end of a USB cable, and the
# attempt leaves the interface with no address rather than the one assigned.
[keyfile]
unmanaged-devices=interface-name:usb0;interface-name:usb1
CONF
echo "usb0 marked unmanaged"

systemctl reload NetworkManager 2>/dev/null || systemctl restart NetworkManager 2>/dev/null
echo "NetworkManager reloaded"

# Remove the hook so this runs exactly once.
sed -i "s| systemd.run=[^ ]*||g; s| systemd.run_success_action=[^ ]*||g; s| systemd.unit=[^ ]*||g" /boot/firmware/cmdline.txt
rm -f /boot/firmware/raptorhab-repair.sh
echo "--- repair complete ---"
exit 0
'

CMDLINE="$BOOT_PATH/cmdline.txt"
CMDLINE_TEXT="$(tr -d '\n' < "$CMDLINE")"

if [[ "$CMDLINE_TEXT" == *"systemd.run="* ]]; then
    warn "cmdline.txt already carries a first-boot hook; not adding another"
else
    CMDLINE_TEXT="$CMDLINE_TEXT systemd.run=/boot/firmware/raptorhab-repair.sh systemd.run_success_action=reboot systemd.unit=kernel-command-line.target"
fi

if [[ $DRY_RUN -eq 1 ]]; then
    echo "  would write $BOOT_PATH/raptorhab-repair.sh"
    echo "  would set cmdline.txt to:"
    echo "    $CMDLINE_TEXT"
    exit 0
fi

export COPYFILE_DISABLE=1
printf '%s' "$REPAIR_BODY" > "$BOOT_PATH/raptorhab-repair.sh"
chmod +x "$BOOT_PATH/raptorhab-repair.sh"
printf '%s\n' "$CMDLINE_TEXT" > "$CMDLINE"
rm -f "$BOOT_PATH"/._* 2>/dev/null || true

ok "repair script staged"
ok "hooked into cmdline.txt"

cat <<'NEXT'

Eject the card and boot the Pi. It applies the fixes, reboots once by itself,
and removes the hook. Check afterwards with:

  cat /var/log/raptorhab-repair.log
  iw dev wlan0 get power_save        # expect: off

NEXT
